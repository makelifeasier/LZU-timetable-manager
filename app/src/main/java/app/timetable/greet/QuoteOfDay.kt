        "天热了，多喝水",
        "秋天的风一吹，就该收心了",
    )

    /**
     * 按日期取一句。同一天永远同一句（当天多次刷新小组件不会跳字），
     * 相邻几天必然不同（按 epochDay 递增取模，池子 48 句 ≈ 一个半月不重样）。
     *
     * 用 [Math.floorMod] 而不是 `%`：1970 年之前的日期 epochDay 是负数，
     * Kotlin 的 `%` 会返回负下标直接崩。
     */
    fun forDate(date: LocalDate): String =
        POOL[Math.floorMod(date.toEpochDay(), POOL.size.toLong()).toInt()]
}
