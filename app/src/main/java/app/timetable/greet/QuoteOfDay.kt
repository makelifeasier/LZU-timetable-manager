    private val POOL: List<String> = listOf(
        // 自习 / 专注
        "先坐下来，再谈状态",
        "写得慢，也是在写",
        "一页一页翻，别急着看结尾",
        "不想学的时候，学十分钟就够",
        "专注半小时，胜过熬一整夜",
        "错题比新题值钱",
        "把不会的，变成会的",
        "自习室里的时间，最实在",
        "困了就眯十分钟，别硬撑",
        "背不下来，就再读一遍",
        "把手机放远一点",
        "一杯热水，一段专注",
        "图书馆四楼，靠窗最好",
        "靠窗的座位，值得早起",

        // 坚持 / 心态
        "慢一点没关系，别停",
        "今天的难题，明天的常识",
        "一切顺利之前，都得先开始",
        "坚持不是拼命，是每天都来",
        "计划列三件就够",
        "完成比完美重要",
        "该交的作业，今天交",
        "累了就出去走十分钟",
        "课表一格一格，日子一天一天",
        "别和昨天的自己较劲",
        "有些事做完，就轻松了",
        "考试是检验，不是审判",
