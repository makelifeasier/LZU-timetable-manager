package app.timetable.greet

import java.time.LocalDate

/**
 * 每日一句。**离线**：句子写死在代码里，不联网、不请求接口、不占任何权限。
 *
 * 定位是"自习室里抬头看一眼"的小句子：短（≤20 字，够小组件单行显示）、
 * 不说教、不喊口号、不涉及宗教与政治。所以池子里大量是天气与季节的观察
 * （兰州的风、秋天的银杏、冬天的被窝）—— 这类句子读起来像旁边的人随口说的，
 * 而不是 App 在给你上课。
 */
